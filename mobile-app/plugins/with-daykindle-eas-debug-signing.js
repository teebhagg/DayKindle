const { withAppBuildGradle } = require('@expo/config-plugins');

const PLUGIN_MARKER = '// @generated by with-daykindle-eas-debug-signing';

const SIGNING_CREDENTIALS_SETUP = `${PLUGIN_MARKER}
def dayKindleEasDebugSigning = null
def dayKindleCredentialsFile = rootProject.file('../credentials.json')
if (dayKindleCredentialsFile.exists()) {
    def dayKindleCredentials
    try {
        dayKindleCredentials = new groovy.json.JsonSlurper().parse(dayKindleCredentialsFile)
    } catch (Exception ignored) {
        throw new GradleException('Could not parse mobile-app/credentials.json for Android debug signing.')
    }

    def dayKindleKeystore = dayKindleCredentials?.android?.keystore
    def dayKindleRequiredFields = ['keystorePath', 'keystorePassword', 'keyAlias', 'keyPassword']
    if (dayKindleKeystore == null || dayKindleRequiredFields.any { !dayKindleKeystore[it]?.toString()?.trim() }) {
        throw new GradleException('mobile-app/credentials.json must contain Android keystorePath, keystorePassword, keyAlias, and keyPassword values.')
    }

    def dayKindleKeystoreFile = new File(dayKindleKeystore.keystorePath.toString())
    if (!dayKindleKeystoreFile.isAbsolute()) {
        dayKindleKeystoreFile = new File(rootProject.projectDir.parentFile, dayKindleKeystore.keystorePath.toString())
    }
    if (!dayKindleKeystoreFile.isFile()) {
        throw new GradleException('The Android keystore referenced by mobile-app/credentials.json was not found.')
    }

    dayKindleEasDebugSigning = [
        storeFile: dayKindleKeystoreFile,
        storePassword: dayKindleKeystore.keystorePassword.toString(),
        keyAlias: dayKindleKeystore.keyAlias.toString(),
        keyPassword: dayKindleKeystore.keyPassword.toString()
    ]
}
`;

const SIGNING_CONFIGS_ANCHOR = [
  '    signingConfigs {',
  '        debug {',
  "            storeFile file('debug.keystore')",
  "            storePassword 'android'",
  "            keyAlias 'androiddebugkey'",
  "            keyPassword 'android'",
  '        }',
  '    }',
].join('\n');

const SIGNING_CONFIGS_WITH_EAS = [
  '    signingConfigs {',
  '        debug {',
  "            storeFile file('debug.keystore')",
  "            storePassword 'android'",
  "            keyAlias 'androiddebugkey'",
  "            keyPassword 'android'",
  '        }',
  '        if (dayKindleEasDebugSigning != null) {',
  "            create('dayKindleEasDebug') {",
  '                storeFile dayKindleEasDebugSigning.storeFile',
  '                storePassword dayKindleEasDebugSigning.storePassword',
  '                keyAlias dayKindleEasDebugSigning.keyAlias',
  '                keyPassword dayKindleEasDebugSigning.keyPassword',
  '            }',
  '        }',
  '    }',
].join('\n');

const DEBUG_BUILD_TYPE_ANCHOR = [
  '        debug {',
  '            signingConfig signingConfigs.debug',
  '        }',
].join('\n');

const DEBUG_BUILD_TYPE_WITH_EAS = [
  '        debug {',
  '            signingConfig dayKindleEasDebugSigning != null ? signingConfigs.dayKindleEasDebug : signingConfigs.debug',
  '        }',
].join('\n');

function replaceExactlyOnce(contents, anchor, replacement, description) {
  const firstIndex = contents.indexOf(anchor);
  if (firstIndex < 0 || contents.indexOf(anchor, firstIndex + anchor.length) >= 0) {
    throw new Error(`Could not safely update Android app Gradle file: expected one ${description} block.`);
  }

  return `${contents.slice(0, firstIndex)}${replacement}${contents.slice(firstIndex + anchor.length)}`;
}

function withDayKindleEasDebugSigning(config) {
  return withAppBuildGradle(config, (modConfig) => {
    let contents = modConfig.modResults.contents;
    if (contents.includes(PLUGIN_MARKER)) {
      return modConfig;
    }

    const androidBlockAnchor = '\nandroid {';
    const androidBlockIndex = contents.indexOf(androidBlockAnchor);
    if (androidBlockIndex < 0 || contents.indexOf(androidBlockAnchor, androidBlockIndex + androidBlockAnchor.length) >= 0) {
      throw new Error('Could not safely update Android app Gradle file: expected one android block.');
    }

    contents = `${contents.slice(0, androidBlockIndex)}\n${SIGNING_CREDENTIALS_SETUP}${contents.slice(androidBlockIndex)}`;
    contents = replaceExactlyOnce(contents, SIGNING_CONFIGS_ANCHOR, SIGNING_CONFIGS_WITH_EAS, 'debug signing configuration');
    contents = replaceExactlyOnce(contents, DEBUG_BUILD_TYPE_ANCHOR, DEBUG_BUILD_TYPE_WITH_EAS, 'debug build type');

    modConfig.modResults.contents = contents;
    return modConfig;
  });
}

module.exports = withDayKindleEasDebugSigning;
